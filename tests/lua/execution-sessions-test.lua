local Sessions=require 'EmberRoutesProbe/ExecutionSessions'
local Claims=require 'EmberRoutesProbe/LaborClaims'
local checks=0
local function check(value,message) checks=checks+1 assert(value,message) end
local function rejected(value,reason,expected,message)
    check(not value and reason==expected,message)
end
local known={bodyStopped=true,effects='KNOWN'}
local unknown={bodyStopped=true,effects='UNKNOWN'}
local s=Sessions.new()
local a=s:acquire('npc-a','order-a','PRODUCTION')
local b=s:acquire('npc-b','order-b','LOGISTICS')
check(a and b and a~=b and s:canAct(a) and s:canAct(b),'two NPCs receive independent grants')
-- Multiple returns need explicit locals to avoid truncating the reason in Lua argument lists.
local function denyAcquire(npc,job,kind,expected,message)
    local value,reason=s:acquire(npc,job,kind) rejected(value,reason,expected,message)
end
denyAcquire('npc-a','other','SELF_CARE','NPC_BUSY','same NPC conflicting owner rejected')
denyAcquire('','job','TEST','IDENTITY_REQUIRED','empty stable identity rejected')
denyAcquire('npc',{},'TEST','IDENTITY_REQUIRED','non-scalar identity rejected')
local snapshot=s:inspect('npc-a')
local firstGeneration=snapshot.generation
snapshot.state='FREE' snapshot.jobId='changed' snapshot.generation=-1
check(s:inspect('npc-a').jobId=='order-a' and s:canAct(a),'diagnostic copies cannot change ownership')
local forged={}
check(not s:canAct(forged) and not Sessions.new():canAct(a),'forged and foreign registry grants rejected')
check(s:requestStop(a,'THIRST') and s:canAct(b) and not s:canAct(a),'stop one NPC without stopping the other')
check(s:requestStop(a,'DANGER') and s:inspect('npc-a').reason=='THIRST','duplicate stop preserves original reason')
local receipt,why=s:confirmStopped(a,{bodyStopped=false,effects='KNOWN'})
rejected(receipt,why,'BODY_NOT_STOPPED','unknown body state retains ownership')
receipt,why=s:confirmStopped(a,{bodyStopped=true})
rejected(receipt,why,'EFFECTS_REQUIRED','physical stop without effect classification rejected')
denyAcquire('npc-a','eat','SELF_CARE','NPC_BUSY','stop request alone does not release ownership')
receipt=s:confirmStopped(a,unknown)
check(receipt and receipt.effects=='UNKNOWN' and receipt.jobId=='order-a','unknown effects returned for business reconciliation')
local nextA=s:acquire('npc-a','drink','SELF_CARE')
check(nextA and s:inspect('npc-a').generation>firstGeneration and not s:canAct(a),'handoff creates a new grant')
check(not s:requestStop(a,'LATE') and not s:complete(a,known) and s:canAct(nextA),'late old grant cannot stop or release new owner')
a.jobId='drink' a.npcId='npc-a'
check(not s:canAct(a),'mutating old token cannot impersonate its successor')
local executed=0
local ok,result,detail=s:dispatch(nextA,function()
    executed=executed+1
    check(not s:canAct(nextA),'no nested authorization during synchronous native call')
    local nested,nestedWhy=s:dispatch(nextA,function() executed=100 end)
    rejected(nested,nestedWhy,'CALL_IN_FLIGHT','nested dispatch denied')
    local closed,closedWhy=s:complete(nextA,known)
    rejected(closed,closedWhy,'CALL_IN_FLIGHT','cannot release while native call is on stack')
    check(s:requestStop(nextA,'DANGER'),'stop can fence new work during a call')
    closed,closedWhy=s:confirmStopped(nextA,known)
    rejected(closed,closedWhy,'CALL_IN_FLIGHT','reentrant stop confirmation cannot grant a new body owner')
    denyAcquire('npc-a','escape','ESCAPE','NPC_BUSY','same-stack replacement rejected')
    return 'effect-observed','native-detail'
end)
check(ok and result=='effect-observed' and detail=='native-detail' and executed==1,'dispatch preserves results and runs exactly once')
check(not s:canAct(nextA) and s:confirmStopped(nextA,known),'stop settles only after native call returned')
local failure=s:acquire('npc-a','eat','SELF_CARE')
ok,result,detail=s:dispatch(failure,function() error('PARTIAL_EFFECT') end)
check(not ok and result=='DISPATCH_ERROR' and string.find(detail,'PARTIAL_EFFECT'),'error is reported rather than hidden')
check(s:inspect('npc-a').state=='STOPPING' and not s:canAct(failure),'error fences further effects without releasing body')
receipt=s:confirmStopped(failure,unknown)
check(receipt and receipt.effects=='UNKNOWN','caller can preserve partial-effect uncertainty on failure')
local active=s:acquire('npc-a','return','LOGISTICS')
receipt,why=s:confirmStopped(active,known)
rejected(receipt,why,'STOP_NOT_REQUESTED','normal completion and stop acknowledgement are distinct')
check(s:complete(active,known) and not s:canAct(active),'normal completion invalidates grant')
local claims=Claims.new()
local claim=claims:acquire('craft-held',1,{'item:42','item:43'})
active=s:acquire('npc-a','craft-held','PRODUCTION')
local ticket=s:beginDrain('SAVE')
check(ticket and not s:canAct(active) and not s:canAct(b),'save barrier fences all current sessions')
local draining=s:drainStatus(ticket)
check(draining.pending==2 and draining.reason=='SAVE','save waits for both explicit stop confirmations')
draining.pending=0
check(s:drainStatus(ticket).pending==2,'drain status is a detached copy')
denyAcquire('npc-c','new','TEST','ADMISSION_CLOSED','save barrier blocks new NPC admission')
local ended,endedWhy=s:endDrain(ticket)
rejected(ended,endedWhy,'SESSIONS_PENDING','barrier cannot reopen while bodies are pending')
check(not s:endDrain({}) and not s:drainStatus({}),'forged barrier token rejected')
check(s:confirmStopped(active,unknown) and claims:valid(claim,'item:42'),'stopping does not release held assets')
check(s:confirmStopped(b,known) and s:drainStatus(ticket).pending==0,'all bodies explicitly settled')
check(s:endDrain(ticket) and not s:endDrain(ticket),'barrier ticket is consumed exactly once')
active=s:acquire('npc-a','after-save','COMPANION')
check(active and s:canAct(active) and claims:valid(claim,'item:43'),'new body owner leaves previous asset custody unchanged')
local second=s:beginDrain('SAVE')
check(not s:endDrain(ticket) and not s:canAct(active),'stale barrier cannot reopen a later save')
check(s:confirmStopped(active,known) and s:endDrain(second),'second barrier completes independently')
ticket=s:beginDrain('EMPTY_SAVE')
check(s:drainStatus(ticket).pending==0 and s:endDrain(ticket),'empty save barrier can complete')
active=s:acquire('npc-a','retire','TEST')
ok=s:dispatch(active,function()
    s:retire()
    check(not s:canAct(active),'world retirement immediately fences dispatch')
    local closed,closedWhy=s:confirmStopped(active,unknown)
    rejected(closed,closedWhy,'CALL_IN_FLIGHT','retirement cannot close an on-stack native call')
end)
check(ok and s:confirmStopped(active,unknown),'retired world accepts final cleanup evidence after unwind')
denyAcquire('npc-a','revive','TEST','WORLD_RETIRED','retired world cannot be reopened')
check(not s:beginDrain('SAVE') and s:retire(),'retirement is permanent and repeatable')
check(claims:valid(claim,'item:42'),'world retirement never destroys business custody')
local fresh=Sessions.new()
local freshToken=fresh:acquire('npc-a','new-world','TEST')
check(fresh:canAct(freshToken) and not fresh:canAct(active) and not s:canAct(freshToken),'same stable ID in new world cannot reuse old authorization')
print(require('EmberRoutesProbe/Build').prefix..' execution sessions: '..checks..' checks; pure protocol, no game bodies')
