local VANILLA_TEX = {}

local function vanillaTex(name)
    local path = VANILLA_TEXTURES[name]
    if not path then return nil end
    local cached = VANILLA_TEX[name]
    if cached ~= nil then return cached or nil end
    local tex = false
    if type(getTexture) == "function" then
        local ok, res = pcall(getTexture, path)
        if ok and res then tex = res end
    end
    VANILLA_TEX[name] = tex
    return tex or nil
end

-- =========================================================================
-- 2. Flat 2.0 Monochromatic Vector Icons (32x32 Antialiased PNGs)
